typedef struct {
    // 数值动态化
    uint16_t pm25_raw; // 原始 PM2.5 数据
    uint16_t humidity; // 湿度百分比
    int16_t temp; // 温度摄氏度
    uint16_t hcho; // 甲醛数值
    uint16_t co2; // CO2数值
    uint16_t tvoc; // TOVC数值


    // 图标/元素显示控制 (bool)
    bool show_wifi; // 显示wifi图标
    bool show_fan; // 显示风扇图标
    bool auto_mode;
    bool show_warning; // 显示警告图标
    bool show_humidity; // 显示湿度逻辑
    bool show_temp; // 显示温度逻辑
    bool show_hcho; // 显示甲醛逻辑
    bool show_co2; // 显示CO2逻辑
    bool show_tovc; // 显示TOVC逻辑
} ui_config_t;

// GUI 事件类型
typedef enum {
    GUI_EVT_PM25,
    GUI_EVT_TEMP_HUM,
    GUI_EVT_ENV, // TVOC, HCHO, CO2
    GUI_EVT_WIFI,
    GUI_EVT_FAN,
    GUI_EVT_WARNING,
    GUI_EVT_AUTO_MODE,
    GUI_EVT_HUMIDITY_ICON,
    GUI_EVT_TEMP_ICON
} gui_evt_type_t;

// GUI 消息结构体
typedef struct {
    gui_evt_type_t type;

    union {
        uint16_t u16_val; // 通用 P2.5 等
        struct {
            int16_t temp;
            uint16_t hum;
        } th;

        struct {
            uint16_t tvoc; // ug/m3
            uint16_t hcho; // ug/m3
            uint16_t eco2; // ppm
        } env;

        bool b_val; // 图标状态
    } data;
} gui_msg_t;


